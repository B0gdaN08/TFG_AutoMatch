-- ============================================================================
-- V1: Esquema completo de AutoMatch.
-- SQL compatible con H2 2.x (desarrollo/tests) y PostgreSQL 16 (produccion).
-- Debe coincidir con las entidades JPA: Hibernate arranca con ddl-auto=validate.
-- ============================================================================

CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email    VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    name     VARCHAR(255),
    role     VARCHAR(255),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE cars (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand                VARCHAR(255),
    model                VARCHAR(255),
    model_year           INTEGER NOT NULL,
    price                DOUBLE PRECISION NOT NULL,
    type                 VARCHAR(255),
    fuel                 VARCHAR(255),
    dgt_label            VARCHAR(255),
    consumption          DOUBLE PRECISION NOT NULL,
    power_cv             INTEGER NOT NULL,
    trunk_liters         INTEGER NOT NULL,
    seats                INTEGER NOT NULL,
    reliability          DOUBLE PRECISION NOT NULL,
    safety               DOUBLE PRECISION NOT NULL,
    equipment            DOUBLE PRECISION NOT NULL,
    maintenance_per_year DOUBLE PRECISION NOT NULL,
    depreciation5y       DOUBLE PRECISION NOT NULL,
    description          VARCHAR(600),
    owner_id             BIGINT,
    status               VARCHAR(255)
);

-- Indices utiles: el catalogo filtra siempre por status, "mis anuncios" por owner_id
-- y la ordenacion por defecto del catalogo es por precio.
CREATE INDEX idx_cars_status   ON cars (status);
CREATE INDEX idx_cars_owner_id ON cars (owner_id);
CREATE INDEX idx_cars_price    ON cars (price);

-- Fotos de cada coche (@ElementCollection con @OrderColumn "position")
CREATE TABLE car_images (
    car_id   BIGINT NOT NULL,
    url      VARCHAR(255),
    position INTEGER NOT NULL,
    PRIMARY KEY (car_id, position),
    CONSTRAINT fk_car_images_car FOREIGN KEY (car_id) REFERENCES cars (id)
);

CREATE TABLE favorites (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    car_id  BIGINT NOT NULL,
    CONSTRAINT uk_favorites_user_car UNIQUE (user_id, car_id),
    CONSTRAINT fk_favorites_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_favorites_car  FOREIGN KEY (car_id)  REFERENCES cars (id)
);
