-- ============================================================================
-- V3: Base de conocimiento de modelos (model_scores).
--
-- Puntuaciones de referencia por marca/modelo/año que el sistema asigna
-- AUTOMATICAMENTE a los anuncios de usuarios (el vendedor ya no las elige):
-- fiabilidad, seguridad y equipamiento (1-10), mantenimiento anual estimado
-- y depreciacion a 5 años. Valores orientativos con fines academicos,
-- elaborados a partir de fuentes publicas (Euro NCAP para seguridad,
-- informes de fiabilidad y precios de mantenimiento del mercado español).
--
-- La resolucion (ModelScoreService) hace matching por marca+modelo con
-- fallback a la media de la marca y a la media global.
-- ============================================================================

CREATE TABLE model_scores (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand                VARCHAR(255) NOT NULL,
    model                VARCHAR(255) NOT NULL,
    model_year           INTEGER NOT NULL,
    reliability          DOUBLE PRECISION NOT NULL,
    safety               DOUBLE PRECISION NOT NULL,
    equipment            DOUBLE PRECISION NOT NULL,
    maintenance_per_year DOUBLE PRECISION NOT NULL,
    depreciation5y       DOUBLE PRECISION NOT NULL
);

